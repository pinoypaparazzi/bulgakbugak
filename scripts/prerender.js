/* Runs after `vite build` (see "build" in package.json).
   1. Renders every route to its own HTML file, e.g. dist/services/index.html
   2. Writes the 404 page, sitemap.xml, robots.txt and _redirects
   3. Removes the temporary server bundle */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'dist');
const ssrDir = path.join(root, 'dist-ssr');

const { render, getRoutes, getRedirects, renderHead, SITE } = await import(
  pathToFileURL(path.join(ssrDir, 'entry-server.js')).href
);

const template = fs.readFileSync(path.join(dist, 'index.html'), 'utf8');
const HEAD_MARKER = /<!--head:[^>]*-->/;
if (!HEAD_MARKER.test(template) || !template.includes('<!--app-html-->')) {
  throw new Error('index.html is missing the <!--head:...--> or <!--app-html--> placeholder');
}

const routes = getRoutes();
for (const route of routes) {
  const html = template
    .replace(HEAD_MARKER, () => renderHead({ ...route.head, path: route.path }))
    .replace('<!--app-html-->', () => render(route.path));
  const file = route.page === 'notfound'
    ? path.join(dist, '404.html')
    : path.join(dist, ...route.path.split('/').filter(Boolean), 'index.html');
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, html);
}

// Sitemap: public pages only (no 404, no draft previews)
const today = new Date().toISOString().slice(0, 10);
const urls = routes
  .filter((r) => r.sitemap !== false && !r.head?.noindex)
  .map((r) => `  <url>\n    <loc>${SITE.url}${r.path}</loc>\n    <lastmod>${r.lastmod || today}</lastmod>\n  </url>`);
fs.writeFileSync(
  path.join(dist, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.join('\n')}\n</urlset>\n`
);
fs.writeFileSync(path.join(dist, 'robots.txt'), `User-agent: *\nAllow: /\n\nSitemap: ${SITE.url}/sitemap.xml\n`);

// Redirects for blog posts whose URL changed (Netlify format)
const redirects = getRedirects().map((r) => `${r.from}  ${r.to}  301`);
fs.writeFileSync(path.join(dist, '_redirects'), `# Generated by scripts/prerender.js\n${redirects.join('\n')}\n`);

fs.rmSync(ssrDir, { recursive: true, force: true });
console.log(`✓ Pre-rendered ${routes.length} pages, ${urls.length} sitemap URLs, ${redirects.length} redirects`);
